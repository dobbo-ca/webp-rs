// DivRound, lossless_common.h:110. Go and C99 both truncate.
func v16DivRound(a, b int64) int64 {
	if (a < 0) == (b < 0) {
		return (a + b/2) / b
	}
	return (a - b/2) / b
}

// FastSLog2Slow_C, lossless_enc.c:252.
func v16FastSLog2Slow(v uint32) uint64 {
	if v < approxLogWithCorrectionMax {
		origV := uint64(v)
		logCnt := uint64(bits.Len32(v) - 8) // BitsLog2Floor(v) - 7
		y := uint32(1) << logCnt
		v >>= logCnt
		correction := v16Log2RecipFixed * (origV & uint64(y-1))
		return origV*(uint64(v16Log2Table[v])+logCnt<<v16LogBits) + correction
	}
	// Conversions keep the products unfused.
	return uint64(float64(float64(v16Log2RecipFixedD*float64(v))*clog(float64(v))) + 0.5)
}

// FastLog2Slow_C, lossless_enc.c:284.
func v16FastLog2Slow(v uint32) uint32 {
	if v < approxLogWithCorrectionMax {
		origV := v
		logCnt := uint32(bits.Len32(v) - 8) // BitsLog2Floor(v) - 7
		y := uint32(1) << logCnt
		v >>= logCnt
		log2 := v16Log2Table[v] + logCnt<<v16LogBits
		if origV >= approxLogMax {
			correction := v16Log2RecipFixed * uint64(origV&(y-1))
			log2 += uint32(v16DivRound(int64(correction), int64(origV)))
		}
		return log2
	}
	return uint32(float64(v16Log2RecipFixedD*clog(float64(v))) + 0.5)
}

// VP8LFastLog2, lossless_common.h:98.
func v16FastLog2(v uint32) uint32 {
	if v < logLookupIdxMax {
		return v16Log2Table[v]
	}
	return v16FastLog2Slow(v)
}

// VP8LFastSLog2, lossless_common.h:102.
func v16FastSLog2(v uint32) uint64 {
	if v < logLookupIdxMax {
		return v16SLog2Table[v]
	}
	return v16FastSLog2Slow(v)
}

// CombinedShannonEntropy_C, lossless_enc.c:320; x and y hold 256.
// The SSE2 and AVX2 versions add the same terms mod 2^64.
func v16CombinedShannonEntropy(x, y []uint32) uint64 {
	var retval uint64
	var sumX, sumXY uint32
	x, y = x[:256], y[:256]
	for i := 0; i < 256; i++ {
		xi := x[i]
		if xi != 0 {
			xy := xi + y[i]
			sumX += xi
			retval += v16FastSLog2(xi)
			sumXY += xy
			retval += v16FastSLog2(xy)
		} else if y[i] != 0 {
			sumXY += y[i]
			retval += v16FastSLog2(y[i])
		}
	}
	return v16FastSLog2(sumX) + v16FastSLog2(sumXY) - retval
}

// ShannonEntropy_C, lossless_enc.c:342; n is len(x).
func v16ShannonEntropy(x []uint32) uint64 {
	var retval uint64
	var sumX uint32
	for _, xi := range x {
		if xi != 0 {
			sumX += xi
			retval += v16FastSLog2(xi)
		}
	}
	return v16FastSLog2(sumX) - retval
}

