	VTRN1 T3.S4, T1.S4, RB.S4 \
	VTRN2 T3.S4, T1.S4, RD.S4

// TTransform butterfly across A..D.
#define HAD(RA, RB, RC, RD, T0, T1, T2, T3) \
	VADD RC.H8, RA.H8, T0.H8 \
	VSUB RC.H8, RA.H8, T3.H8 \
