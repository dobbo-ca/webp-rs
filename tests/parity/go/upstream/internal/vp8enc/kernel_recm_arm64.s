	VSUB T1.H8, T0.H8, RD.H8 \
	VADD T2.H8, T3.H8, RB.H8 \
	VSUB T2.H8, T3.H8, RC.H8

// Weighted sum of H0..H3 by V1..V4; low halves to QL, high to QH.
