// Transpose the 4x4 int16 block in each half of A..D.
#define TR4(RA, RB, RC, RD, T0, T1, T2, T3) \
	VTRN1 RB.H8, RA.H8, T0.H8 \
	VTRN2 RB.H8, RA.H8, T1.H8 \
